#!/usr/bin/env python3
"""Which functions the PC port links, from a port build, as a committed list.

PORTED is measured on a port build (port/tools/linkage.py reads
build/port/walk_window.map) and CI on main has no such build, so the headline is a
STAMP in config/port_linkage.json. This tool produces the per-function half of the
same measurement: config/port_linked_functions.txt, one ``module:0xaddr`` key per
function whose translation unit is linked into walk_window, using the identical
rule linkage.py applies (a source stem whose object appears in the map).
tools/chaos_db_ci.py publishes a key found in that file as ``ported: true`` on the
function's record, so the Atlas can colour by PORTED without a port build.

The port tree and this tree can fold translation units differently (the port
branches lag main's TU folding), so the mapping runs in the PORT tree: the tree's
own srcpath resolves each symbol to the file that owns it there, and the key is
(module, address), which survives any renaming or refolding between the two.

    python tools/port_linked_functions.py --root <port tree> --branch <branch>
        [--out config/port_linked_functions.txt]
        [--stamp]        # also rewrite the numbers and provenance in
                         # config/port_linkage.json (its _comment is left alone)
        [--basis TEXT]   # with --stamp: the stamp's `basis` sentence

Run it on a tree whose build/port/walk_window.map was linked from the tree's own
HEAD with a clean src/. It refuses a dirty src/ or a missing map. The commit is the
tree's HEAD (11 characters) and goes into both outputs, which is how chaos_db_ci
knows the list and the stamp describe one build.

Needs the tree's own tools/ (srcpath, relocs) and port/tools/linkage.py; no
compiler, no ROM, no network.
"""
import argparse
import datetime
import importlib.util
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent
FUNC_RE = re.compile(
    r"^(\S+)\s+kind:function\((?:arm|thumb),size=0x([0-9a-fA-F]+)\).*?addr:0x([0-9a-fA-F]+)")
HEADER = """\
# Functions whose translation unit is linked into the PC port (walk_window).
# GENERATED by tools/port_linked_functions.py from a port build. Do not hand-edit.
# One `module:0xaddr` per line, the same key function-authors.json uses.
# tools/chaos_db_ci.py believes this file only while `commit` equals the commit in
# config/port_linkage.json. Re-stamp both together with `--stamp`.
"""


def git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


def load_linkage(root):
    path = root / "port" / "tools" / "linkage.py"
    spec = importlib.util.spec_from_file_location("port_linkage_tool", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", required=True, help="the port tree that was built")
    ap.add_argument("--branch", required=True, help="the port branch the tree is")
    ap.add_argument("--out", default=str(REPO / "config" / "port_linked_functions.txt"))
    ap.add_argument("--stamp", action="store_true",
                    help="also rewrite config/port_linkage.json's numbers and provenance")
    ap.add_argument("--basis", default=None, help="the stamp's `basis` sentence")
    args = ap.parse_args()

    root = pathlib.Path(args.root).resolve()
    mapfile = root / "build" / "port" / "walk_window.map"
    if not mapfile.is_file():
        sys.exit(f"no {mapfile}: build walk_window in that tree first")
    dirty = git(root, "status", "--porcelain", "--", "src", "config", "include")
    if dirty:
        sys.exit("refusing: src/, config/ or include/ is dirty in the port tree, so the "
                 "map is not a measurement of its HEAD:\n" + dirty)
    commit = git(root, "rev-parse", "--short=11", "HEAD")
    measured = datetime.datetime.fromtimestamp(
        mapfile.stat().st_mtime, datetime.timezone.utc).strftime("%Y-%m-%d")

    linkage = load_linkage(root)
    matched = linkage.matched_index(str(root))
    linked_stems = set()
    for _sym, obj in linkage.map_symbols(str(mapfile)):
        stem = pathlib.Path(pathlib.Path(obj).stem).stem
        if stem in matched:
            linked_stems.add(stem)

    # The tree's own resolver, not this tree's: sys.path[0] is this script's directory,
    # which would import the wrong srcpath. Drop it before the port tree's goes in.
    sys.path[:] = [p for p in sys.path if pathlib.Path(p or ".").resolve() != HERE]
    sys.path.insert(0, str(root / "tools"))
    import relocs as RL  # noqa: E402
    import srcpath as SP  # noqa: E402

    keys, universe = set(), set()
    for sym, label in RL.module_universe():
        for line in sym.read_text(errors="ignore").splitlines():
            m = FUNC_RE.match(line)
            if not m:
                continue
            addr = int(m.group(3), 16)
            universe.add(f"{label}:0x{addr:08x}")
            f = SP.path_for(m.group(1))
            if f is not None and pathlib.Path(f).stem in linked_stems:
                keys.add(f"{label}:0x{addr:08x}")

    out = pathlib.Path(args.out)
    out.write_text(
        HEADER
        + f"# branch: {args.branch}\n# commit: {commit}\n# measuredAt: {measured}\n"
        + f"# linkedTus: {len(linked_stems)}\n# matchedTus: {len(matched)}\n"
        + f"# functions: {len(keys)}\n# universe: {len(universe)}\n"
        + "\n".join(sorted(keys)) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(keys)} of {len(universe)} functions ({100.0 * len(keys) / len(universe):.2f}%) across {len(linked_stems)} linked of "
          f"{len(matched)} matched TUs ({100.0 * len(linked_stems) / len(matched):.2f}%) "
          f"@ {args.branch} {commit}, map of {measured}")

    if args.stamp:
        stamp_path = REPO / "config" / "port_linkage.json"
        stamp = json.loads(stamp_path.read_text(encoding="utf-8"))
        stamp.update({"linkedTus": len(linked_stems), "matchedTus": len(matched),
                      "measuredAt": measured, "branch": args.branch, "commit": commit,
                      "stale": False})
        if args.basis:
            stamp["basis"] = args.basis
        stamp_path.write_text(json.dumps(stamp, indent=2, ensure_ascii=False) + "\n",
                              encoding="utf-8", newline="\n")
        print(f"rewrote {stamp_path}")


if __name__ == "__main__":
    main()
