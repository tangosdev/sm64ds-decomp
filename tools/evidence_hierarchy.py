RAW_CAST = re.compile(
    r"\*\s*\(\s*(?P<ty>(?:const\s+|volatile\s+|struct\s+|unsigned\s+|signed\s+)*"
    r"[A-Za-z_]\w*\s*\**)\s*\)\s*\(\s*(?:\(\s*[A-Za-z_][\w \*]*\s*\)\s*)*"
    r"(?P<base>[A-Za-z_]\w*)\s*\+\s*(?P<off>0x[0-9a-fA-F]+|\d+)\s*\)")
RAW_INDEX = re.compile(r"(?<![\w>.])(?P<base>[A-Za-z_]\w*)\s*"
                       r"\[\s*(?P<idx>0x[0-9a-fA-F]+|\d+)\s*\]")
DEF_OPEN = re.compile(r"(?<![\w:])(?P<name>[A-Za-z_]\w*(?:::~?[A-Za-z_]\w*)?)\s*"
                      r"\((?P<params>[^;{}()]*(?:\([^()]*\)[^;{}()]*)*)\)\s*"
                      r"(?:const\s*)?\{")
NOT_A_DEF = {"if", "while", "for", "switch", "return", "sizeof", "catch", "do"}
DECL_ALIAS = re.compile(
    r"^\s*(?P<ty>(?:const\s+|volatile\s+|struct\s+|unsigned\s+|signed\s+)*"
    r"[A-Za-z_]\w*)\s*(?P<stars>\*+)\s*(?P<name>[A-Za-z_]\w*)\s*=\s*(?P<rhs>.+)$",
    re.S)
PARAM_PTR = re.compile(
    r"^\s*(?:const\s+|volatile\s+|struct\s+|unsigned\s+|signed\s+)*"
    r"(?P<ty>[A-Za-z_]\w*)\s*(?P<stars>\*+)\s*(?P<name>[A-Za-z_]\w*)\s*$")


def iter_definitions(text):
    """(name, body, first_param(name, elem_width), start_line) for every
    function definition in a file.

    Necessary because a file's symbol is not always the identifier that is
    defined in it: src/_ZN10ChainChomp13InitResourcesEv.cpp defines
    `int ChainChomp::InitResources()`, with `this` aliased to a local `c`.
    Requiring the mangled name would have found zero accesses there -- the same
    shape of miss that section 2 of the plan is about.
    """
    for m in DEF_OPEN.finditer(text):
        name = m.group("name")
        if name.split("::")[0] in NOT_A_DEF:
            continue
        k = m.end() - 1
        depth, e = 0, k
        while e < len(text):
            if text[e] == "{":
                depth += 1
            elif text[e] == "}":
                depth -= 1
                if depth == 0:
                    break
            e += 1
        pm = PARAM_PTR.match(m.group("params").split(",")[0])
        first = None
        if pm:
            first = (pm.group("name"),
                     type_width(pm.group("ty")) if len(pm.group("stars")) == 1 else 4)
        yield name, text[k + 1:e], first, text.count("\n", 0, k) + 1


def scan_raw_offsets(text):
    """Raw offset accesses whose base provably still holds the entry `this`.

    Two forms, both carrying a width:
        *(T *)(this + 0xNN)     -- the cast form, T gives the width
        this[N]                 -- the array form, the pointer's element type
                                   gives the width and N * width the offset
    `this` means: the first parameter of a free function with the mangled name,
    OR the C++ `this` of a method, OR a local declared as a pure cast of one of
    those (`unsigned char *c = (unsigned char *)((void *)this);`).  Anything
    reached by arithmetic is dropped, never guessed -- section 3 of the plan.
    """
    out = []
    for _name, body, first, start in iter_definitions(text):
        nocom = re.sub(r"//[^\n]*", " ", strip_block_comments(body))
        this_names = {"this": 1}
        if first and first[0]:
            this_names[first[0]] = first[1]
        pos = 0
        for stmt in nocom.split(";"):
            stmt_start, pos = pos, pos + len(stmt) + 1
            dm = DECL_ALIAS.match(stmt)
            if dm and _value_ident(dm.group("rhs")) in this_names:
                w = type_width(dm.group("ty")) if len(dm.group("stars")) == 1 else 4
                this_names[dm.group("name")] = w
                continue
            for m in RAW_CAST.finditer(stmt):
                if m.group("base") not in this_names:
                    continue
                # The form is `*(T *)(this + off)`: the cast is to T*, but the
                # access is to T, so the width is sizeof(T), not sizeof(T*).
                # Sizing the cast type directly made type_width see the `*` and
                # return 4 for every access -- all 455 rows that carried a
                # source-evidence width reported 4, including `*(u8 *)(c+0xdc8)`,
                # and 330 of them were used to confirm a base field's width.
                # Strip exactly one level of indirection; `*(T **)(...)` still
                # sizes as a pointer, which is correct.
                ty = normalize_type(m.group("ty"))
                pointee = ty[:-1].strip() if ty.endswith("*") else ty
                w = type_width(pointee)
                if w is not None:
                    out.append((int(m.group("off"), 0), w, pointee,
                                start + nocom.count("\n", 0, stmt_start + m.start())))
            for m in RAW_INDEX.finditer(stmt):
                ew = this_names.get(m.group("base"))
                if not ew:
                    continue
                out.append((int(m.group("idx"), 0) * ew, ew, "[]*%d" % ew,
                            start + nocom.count("\n", 0, stmt_start + m.start())))
    return out


