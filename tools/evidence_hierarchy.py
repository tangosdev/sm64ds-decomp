def load_rtti_edges(root, stats):
    """Inheritance edges the ROM states outright, translated into tree names.

    This is a deliberate reversal of what this pass used to say about itself: that
    it was "source+config only" and that "the ROM is pass 3's authority, not pass
    2's".  That held while the ROM's typeinfo was undelinked.  It no longer is --
    tools/rtti_extract.py reads all 429 records and 413 edges out of arm9 and the
    overlays, and tools/rtti_symbols.py landed the _ZTI/_ZTS symbols into config.
    An edge that the ROM stores as a pointer is not evidence to be ranked against
    other evidence; it is the answer, so `rtti` sits above `reference_header`.
    The fader family is why that ordering matters: four include/ headers agree with
    each other and disagree with the ROM.

    The join is **vtable-only**.  build/rtti_reconcile.json also carries aliases
    inferred by majority vote over edges, and those are good enough to report with,
    but not to feed back in here: an alias derived from an edge, used to admit that
    same edge as top-rank evidence, is circular.  Only records whose vtable carries
    a `_ZTV<TreeName>` symbol are used, and only when BOTH ends of the edge have one.

    Degrades to nothing (not an error) when build/rtti.json is absent -- a cold
    clone has no extracted/ and cannot regenerate it.
    """
    path = os.path.join(root, "build", "rtti.json")
    if not os.path.exists(path):
        stats["rtti_json_absent"] = 1
        return []
    try:
        data = json.load(open(path, encoding="utf-8"))
    except Exception as exc:                                    # noqa: BLE001
        stats["rtti_json_unreadable"] = 1
        return []

    # load_symbols keys modules by path relative to config/ ("arm9",
    # "arm9/overlays/ov002"), while rtti.json names them as dsd does ("arm9",
    # "ov002").  Keying on the raw string matched arm9 only and silently dropped
    # every overlay record -- 31 classes named instead of 255.  Normalize to the
    # last path component, which is the module name in both vocabularies.
    addr_names, _f, _d = load_symbols(root)
    by_mod = defaultdict(list)
    for (mod, addr), names in addr_names.items():
        by_mod[(mod.rsplit("/", 1)[-1], addr)].extend(names)

    tree = {}                       # ROM class name -> tree class name
    for key, r in sorted(data.get("records", {}).items()):
        if not r.get("vtable"):
            continue
        for n in sorted(by_mod.get((r["module"], int(r["vtable"], 16)), [])):
            if n.startswith("_ZTV"):
                p = split_nested(n[4:-1] if n[4:5] == "N" and n.endswith("E")
                                 else n[4:])
                if p:
                    tree[r["name"]] = "::".join(p)
                    break
    stats["rtti_records"] = len(data.get("records", {}))
    stats["rtti_edges_in_rom"] = len(data.get("edges", []))
    stats["rtti_classes_named_by_a_ztv_symbol"] = len(tree)

    # `hierarchy` holds ONE base per class, so a multiple-inheritance class must
    # contribute only its primary -- the base subobject at offset 0.  Emitting all
    # of them puts two rank-0 edges on one class, and the picker then takes the
    # sorted-first: ModelAnim flipped from Model (offset 0) to Animation (offset
    # 0x50) and its confidence dropped to low, reporting a manufactured conflict.
    # The secondary bases are real and are counted here, but they belong to a
    # structure that can represent them, which this one cannot.
    by_derived = defaultdict(list)
    for e in data.get("edges", []):
        by_derived[e["derived"]].append(e)

    out = []
    for derived, edges in sorted(by_derived.items()):
        primary = [e for e in edges if e.get("offset", 0) == 0] or edges
        if len(edges) > 1:
            stats["rtti_multiple_inheritance_classes"] += 1
            stats["rtti_secondary_bases_not_representable"] += len(edges) - len(primary)
        e = primary[0]
        d, b = tree.get(e["derived"]), tree.get(e["base"])
        if not d or not b or d == b:
            stats["rtti_edges_skipped_end_unnamed"] += 1
            continue
        out.append((d, b, "ROM typeinfo %s -> %s (offset 0x%x)"
                    % (e["derived_key"], e["base_key"], e.get("offset", 0))))
    stats["rtti_edges_usable"] = len(out)
    return out


def build(root, seed_path):
    inc = os.path.join(root, "include")
    src = os.path.join(root, "src")
    stats = Counter()
    notes = []

    # ---- 1. headers ------------------------------------------------------
    headers = {}
    for fn in sorted(os.listdir(inc)):
        if not fn.endswith(".h"):
            continue
        stats["headers_scanned"] += 1
        hi = parse_header(os.path.join(inc, fn), "include/" + fn)
        headers[hi.cls] = hi
        stats["headers_" + hi.kind] += 1

    bannered = sorted(c for c, h in headers.items() if h.kind == "bannered")
    reference = sorted(c for c, h in headers.items() if h.kind == "reference")
    for c in bannered:
        h = headers[c]
        stats["bannered_fields_named"] += len(h.fields)
        stats["bannered_fields_padding"] += h.pads
        stats["bannered_fields_no_offset"] += h.no_offset
        stats["bannered_fields_unknown_width"] += h.unknown_width
        if not h.struct_found:
            stats["bannered_headers_with_no_struct_block"] += 1
    for c in reference:
        h = headers[c]
        stats["reference_fields_named"] += len(h.fields)
        stats["reference_fields_no_offset"] += h.no_offset
        if not h.struct_found:
            stats["reference_headers_with_no_struct_block"] += 1

    # ---- 2. symbols ------------------------------------------------------
    addr_names, sym_files, sym_dups = load_symbols(root)
    stats["symbols_files"] = sym_files
    stats["symbols_ambiguous_across_modules"] = sym_dups
    stats["symbols_addresses"] = len(addr_names)
    stats["symbols_ztv"] = sum(1 for ns in addr_names.values()
                               for n in ns if n.startswith("_ZTV"))
    stats["symbols_zti"] = sum(1 for ns in addr_names.values()
                               for n in ns if n.startswith("_ZTI"))

    alias, data_alias, alias_groups = build_vtable_alias_map(addr_names, set(headers))
    stats["vtable_alias_groups"] = len(alias_groups)

    # ---- 3. read the ctor/dtor corpus ------------------------------------
    src_files = sorted(os.listdir(src))
    dtor_files, ctor_files, anon_files = {}, {}, {}
    for f in src_files:
        m = DTOR_FILE.match(f)
        if m:
            p = split_nested(m.group(1))
            if p:
                dtor_files.setdefault("::".join(p), {})[m.group(2)] = f
            continue
        m = CTOR_FILE.match(f)
        if m:
            p = split_nested(m.group(1))
            if p:
                ctor_files.setdefault("::".join(p), {})[m.group(2)] = f
            continue
        m = ANON_FILE.match(f)
        if m:
            anon_files[m.group(1)] = f
    stats["dtor_TUs_present"] = sum(len(v) for v in dtor_files.values())
    stats["dtor_classes_present"] = len(dtor_files)
    stats["ctor_TUs_present"] = sum(len(v) for v in ctor_files.values())

    cache = {}

    def read_src(f):
        if f not in cache:
            cache[f] = open(os.path.join(src, f), encoding="utf-8",
                            errors="replace").read()
        return cache[f]

    # 3a. analyse every D1/D2 and C1/C2 definition
    dtor_info = {}          # (cls, kind) -> info
    for cls, kinds in sorted(dtor_files.items()):
        for kind in ("2", "1"):
            f = kinds.get(kind)
            if not f:
                continue
            stats["dtor_TUs_analysed"] += 1
            info = analyse_body(read_src(f), f[:f.rindex(".")])
            if info is None:
                stats["dtor_TUs_without_a_parsable_definition"] += 1
                continue
            info["file"] = f
            dtor_info[(cls, kind)] = info
    ctor_info = {}
    for cls, kinds in sorted(ctor_files.items()):
        for kind in ("2", "1"):
            f = kinds.get(kind)
            if not f:
                continue
            stats["ctor_TUs_analysed"] += 1
            info = analyse_body(read_src(f), f[:f.rindex(".")])
            if info is None:
                stats["ctor_TUs_without_a_parsable_definition"] += 1
                continue
            info["file"] = f
            ctor_info[(cls, kind)] = info

    # 3b. vtable literal -> owning class, learned from *named* destructors
    vt_owner = defaultdict(set)
    for (cls, _k), info in sorted(dtor_info.items()):
        if info["vptrs"]:
            vt_owner[info["vptrs"][0][0]].add(alias.get(cls, cls))
    stats["vtable_literals_owned"] = sum(1 for v in vt_owner.values() if len(v) == 1)
    stats["vtable_literals_ambiguous"] = sum(1 for v in vt_owner.values() if len(v) > 1)
    vt_owner = {k: v for k, v in vt_owner.items() if len(v) == 1}

    # 3c. resolve the *anonymous* destructors that are actually called as bases.
    #     Fixpoint, because an anonymous base dtor can itself call another one
    #     (Goomba -> func_ov002_020aedbc -> func_ov002_020aed18 -> Actor).
    candidates = set()
    anon_callers = defaultdict(set)
    for (cls, _k), info in sorted(dtor_info.items()):
        for fn, _l in info["calls"]:
            if fn.startswith("func_"):
                candidates.add(fn)
                anon_callers[fn].add(cls)
    anon_owner, anon_info, anon_unresolved = {}, {}, set()
    seen = set()
    while True:
        todo = sorted(candidates - seen)
        if not todo:
            break
        for fn in todo:
            seen.add(fn)
            f = anon_files.get(fn)
            if f is None:
                anon_unresolved.add(fn)
                continue
            info = analyse_body(read_src(f), fn)
            if info is None:
                anon_unresolved.add(fn)
                continue
            info["file"] = f
            anon_info[fn] = info
            for c, _l in info["calls"]:
                if c.startswith("func_"):
                    candidates.add(c)
                    anon_callers[c].add(fn)
            if not info["vptrs"]:
                anon_unresolved.add(fn)
                continue
            cls, _how = resolve_vtable_symbol(info["vptrs"][0][0], alias, vt_owner, data_alias)
            if cls:
                anon_owner[fn] = cls
            else:
                anon_unresolved.add(fn)

    # Back-resolution: an unnamed base destructor called at offset 0 by class D
    # IS the destructor of D's base.  When D's base is fixed independently by a
    # de-bannered reference header, that names the unnamed function.
    # `func_020354d0` is reached this way: WithMeshClsn's dtor calls it at offset
    # 0 and include/WithMeshClsn.h says `struct WithMeshClsn : BgCh`, so the
    # function is BgCh's D1.  Only accepted when every reference-header caller
    # agrees.
    ref_base = {c: headers[c].base for c in reference if headers[c].base}
    for fn in sorted(anon_unresolved):
        proposals = {ref_base[d] for d in anon_callers.get(fn, ()) if d in ref_base}
        if len(proposals) == 1:
            anon_owner[fn] = alias.get(next(iter(proposals)), next(iter(proposals)))
            stats["anon_base_dtors_resolved_via_reference_base"] += 1
    anon_unresolved -= set(anon_owner)
    stats["anon_base_dtor_candidates"] = len(seen)
    stats["anon_base_dtors_resolved"] = len(anon_owner)
    stats["anon_base_dtors_unresolved"] = len(anon_unresolved)

    # ---- 4. edges --------------------------------------------------------
    edges = defaultdict(lambda: defaultdict(list))
    edge_src_count = Counter()

    def add_edge(d, b, source, ev):
        d = alias.get(d, d)
        b = alias.get(b, b)
        if not d or not b or d == b:
            return
        edges[d][b].append((source, ev))
        edge_src_count[source] += 1

    # 4a0. RTTI -- the ROM's own statement, and the only source here that is not a
    #      reconstruction.  See load_rtti_edges() for why this outranks
    #      reference_header and why the join is vtable-only.
    for d, b, ev in load_rtti_edges(root, stats):
        add_edge(d, b, "rtti", ev)

    # 4a. reference headers -- the authority among reconstructions
    for cls in reference:
        h = headers[cls]
        if h.base:
            add_edge(cls, h.base, "reference_header",
                     "%s:%d" % (h.path, h.base_line))

    # 4b. vptr chains.  Two passes: the first learns which vtable-literal class
    #     names ever appear as a *non-first* store (so are genuinely bases);
    #     names that only ever appear first are the class's own vtable under the
    #     ROM's original spelling (`daObjFlMaruta_c` for FallBlockLll) and must
    #     not become a self-edge.
    def chain_of(info):
        out = []
        for vsym, line in info["vptrs"]:
            c, how = resolve_vtable_symbol(vsym, alias, vt_owner, data_alias)
            out.append((c, line, vsym, how))
        return out

    inner_names = set()
    for info in list(dtor_info.values()) + list(anon_info.values()) + list(ctor_info.values()):
        ch = chain_of(info)
        for c, _l, _s, _h in ch[1:]:
            if c:
                inner_names.add(c)

    def emit_chain(cls, info, source, reverse=False, base_resolver=None,
                   first_call=False):
        ch = [x for x in chain_of(info) if x[0]]
        if reverse:
            ch = ch[::-1]
        walk = []
        if ch and ch[0][0] != cls and ch[0][0] not in inner_names:
            # the class's own vtable, spelled with the ROM's original name
            stats["vtable_self_aliases_absorbed"] += 1
            ch = ch[1:]
        for c, line, vsym, _how in ch:
            walk.append((c, line, vsym))
        if not walk or walk[0][0] != cls:
            walk.insert(0, (cls, None, None))
        base = None
        for fn, line in (info["calls"] if not first_call else info["calls"][:1]):
            b, _how = base_resolver(fn, anon_owner, alias)
            if b and alias.get(b, b) != cls:
                base = (alias.get(b, b), line, fn)
                if first_call:
                    break
        f = info["file"]
        for i in range(len(walk) - 1):
            add_edge(walk[i][0], walk[i + 1][0], source,
                     "src/%s:%s vptr store %s" % (f, walk[i + 1][1], walk[i + 1][2]))
        if base:
            add_edge(walk[-1][0], base[0],
                     "dtor_chain" if source == "dtor_vptr_chain" else source,
                     "src/%s:%s calls %s" % (f, base[1], base[2]))
        return bool(walk[1:]) or bool(base)

    for (cls, _k), info in sorted(dtor_info.items()):
        if emit_chain(cls, info, "dtor_vptr_chain", base_resolver=resolve_dtor_callee):
            stats["dtor_TUs_yielding_an_edge"] += 1
    for fn, info in sorted(anon_info.items()):
        cls = anon_owner.get(fn)
        if cls and emit_chain(cls, info, "dtor_vptr_chain",
                              base_resolver=resolve_dtor_callee):
            stats["anon_dtors_yielding_an_edge"] += 1
    for (cls, _k), info in sorted(ctor_info.items()):
        # ctors store base-most vptr first and call the base ctor first
        if emit_chain(cls, info, "ctor_chain", reverse=True,
                      base_resolver=resolve_ctor_callee, first_call=True):
            stats["ctor_TUs_yielding_an_edge"] += 1

    # 4c. cpp shims -- weak, and only over class-attributable .cpp
    universe = set(headers) | set(dtor_files) | set(ctor_files) | set(edges)
    for d in list(edges):
        universe |= set(edges[d])
    universe = {alias.get(c, c) for c in universe} | universe
    ctor_dtor_paths = {v for kinds in dtor_files.values() for v in kinds.values()}
    ctor_dtor_paths |= {v for kinds in ctor_files.values() for v in kinds.values()}
    shim_files = [(class_of_mangled_symbol(f[:f.rindex(".")]), f)
                  for f in src_files if f.endswith(".cpp") and f.startswith("_ZN")]
    shim_files = [(c, f) for c, f in shim_files if c in universe]
    for owner, f in shim_files:
        text = read_src(f)
        for m in re.finditer(
                r"(?:struct|class)\s+([A-Za-z_]\w*)\s*:\s*"
                r"(?:public\s+|private\s+|protected\s+|virtual\s+)*([A-Za-z_][\w:]*)\s*\{",
                text):
            d, b = m.group(1), m.group(2)
            if d in universe and b in universe:
                # A shim inside the class's OWN ctor/dtor TU is the declaration
                # that was actually compiled into the matching bytes, so it is
                # evidence about that class.  Elsewhere it is scenery.
                src_kind = ("cpp_dtor_shim"
                            if (f in ctor_dtor_paths and alias.get(d, d) == alias.get(owner, owner))
                            else "cpp_shim")
                add_edge(d, b, src_kind,
                         "src/%s:%d" % (f, text.count("\n", 0, m.start()) + 1))
    stats["cpp_shim_files_scanned"] = len(shim_files)

    # 4d. seed
    seed = {}
    if seed_path and os.path.exists(seed_path):
        try:
            seed = json.load(open(seed_path, encoding="utf-8"))
        except Exception as exc:                            # noqa: BLE001
            notes.append("seed %s unreadable: %s" % (seed_path, exc))
    seed_rel = os.path.relpath(seed_path, root).replace("\\", "/") if seed_path else ""
    for d in sorted(seed):
        add_edge(d, seed[d], "seed_hier_json", seed_rel)
    stats["seed_entries"] = len(seed)

    # ---- 5. pick each class's base ---------------------------------------
    hierarchy = {}
    for d in sorted(edges):
        cands = edges[d]
        best = min(SOURCE_RANK.index(s) for b in cands for s, _ in cands[b])
        winners = sorted(b for b in cands
                         if any(SOURCE_RANK.index(s) == best for s, _ in cands[b]))
        base = winners[0]
        srcs = sorted({s for s, _ in cands[base]})
        ev = sorted("%s %s" % (s, e) for s, e in cands[base]
                    if SOURCE_RANK.index(s) == best)[0]
        # dtor_vptr_chain and dtor_chain come out of the same file, so they are
        # one independent observation, not two.
        groups = {EVIDENCE_GROUP[s] for s in srcs}
        # `rtti` is listed here for the same reason as reference_header, and more
        # so: it is not a reconstruction that happens to be trustworthy, it is the
        # edge the ROM stores.  Without it, a class whose ONLY evidence was the ROM
        # fell past both branches to "low" -- ten classes, including four bannered
        # ones, were downgraded by gaining the best evidence available.
        if {"reference_header", "rtti"} & set(srcs) or len(groups) >= 2:
            conf = "high"
        elif groups & {"dtor", "ctor", "shim_own_tu"}:
            conf = "medium"
        else:
            conf = "low"
        entry = {
            "base": base,
            "evidence": ev,
            "confidence": conf,
            "sources": srcs,
            "all_evidence": sorted("%s %s" % (s, e) for s, e in cands[base]),
        }
        losing = sorted(b for b in cands if b != base)
        if losing:
            entry["rejected"] = {b: sorted("%s %s" % (s, e) for s, e in cands[b])
                                 for b in losing}
        if SOURCE_RANK[best] in FLATTENING_SOURCES:
            entry["caveat"] = ("best evidence is a declaration shim / the seed map; "
                               "those flatten inlined intermediate bases, so this "
                               "may be an ancestor rather than the immediate base")
        if len(winners) > 1:
            entry["confidence"] = "low"
            entry["note"] = ("sources of equal authority name different bases: "
                             + ", ".join(winners))
        hierarchy[d] = entry

    def ancestors(cls):
        out, seen_, cur = [], {cls}, cls
        while cur in hierarchy:
            nxt = hierarchy[cur]["base"]
            if nxt in seen_:
                break
            out.append(nxt)
            seen_.add(nxt)
            cur = nxt
        return out

    anc = {c: ancestors(c) for c in sorted(set(hierarchy) | set(headers))}
    for c in sorted(hierarchy):
        hierarchy[c]["chain"] = anc[c]

    placed = sorted(c for c in bannered if c in hierarchy)
    unplaced = sorted(c for c in bannered if c not in hierarchy)
    reasons = {}
    for c in unplaced:
        why = []
        if c in dtor_files:
            info = dtor_info.get((c, "1")) or dtor_info.get((c, "2"))
            if info is None:
                why.append("dtor TU present but no definition could be parsed")
            elif not info["calls"]:
                why.append("dtor TU present and parsed, but it makes no call "
                           "taking bare `this` -- consistent with a root class "
                           "(no base to destroy)")
            else:
                bits = []
                for fn, _l in sorted(info["calls"]):
                    tail = []
                    sub = anon_info.get(fn)
                    if sub:
                        for vsym, _l2 in sub["vptrs"]:
                            vc = resolve_vtable_symbol(vsym, alias, vt_owner, data_alias)[0]
                            if vc:
                                tail.append(vc)
                    if tail:
                        bits.append("%s (an unnamed destructor whose own vtable "
                                    "literal is unresolvable, but whose chain "
                                    "continues into %s)" % (fn, " : ".join(tail)))
                    else:
                        bits.append(fn)
                why.append("dtor TU present; its bare-`this` callee(s) could not be "
                           "resolved to a class: " + "; ".join(bits))
        else:
            why.append("no ctor/dtor TU in src/ -- no polymorphic evidence at "
                       "all; likely a plain struct or an all-inline class")
        if c in seed:
            why.append("build/hier.json claimed base %s, uncorroborated" % seed[c])
        reasons[c] = "; ".join(why)

    # ---- 6. overlaps ------------------------------------------------------
    offmap = {}
    for cls, h in headers.items():
        if h.kind not in ("bannered", "reference"):
            continue
        m = {}
        for f in h.fields:
            m.setdefault(f.offset, f)
        offmap[cls] = m

    raw = defaultdict(dict)
    raw_multi = set()
    interesting = set(placed)
    for f in src_files:
        if not f.startswith("_ZN"):
            continue
        ext = os.path.splitext(f)[1]
        if ext not in (".c", ".cpp"):
            continue
        c = class_of_mangled_symbol(f[:-len(ext)])
        if c is None:
            continue
        c = alias.get(c, c)
        if c not in interesting:
            continue
        stats["src_TUs_scanned_for_raw_offsets"] += 1
        for off, w, ty, line in scan_raw_offsets(read_src(f)):
            stats["raw_offset_accesses_seen"] += 1
            prev = raw[c].get(off)
            if prev is None:
                raw[c][off] = (w, ty, "src/" + f, line)
            elif prev[0] != w:
                raw_multi.add((c, off))
    stats["raw_offset_distinct_class_offsets"] = sum(len(v) for v in raw.values())
    stats["raw_offset_classes_with_evidence"] = len(raw)
    stats["raw_offset_self_contradictions"] = len(raw_multi)

    conflicts = []
    agreeing = 0
    no_header = Counter()
    for cls in bannered:
        h = headers[cls]
        for f in sorted(h.fields, key=lambda x: (x.offset, x.name)):
            for depth, a in enumerate(anc.get(cls, []), 1):
                am = offmap.get(a)
                if am is None:
                    no_header[a] += 1
                    continue
                g = am.get(f.offset)
                if g is None:
                    continue
                if f.width is None or g.width is None:
                    kind = "unknown_width"
                elif f.width != g.width:
                    kind = "width"
                elif f.sign and g.sign and f.sign != g.sign:
                    kind = "sign"
                else:
                    kind = "agree"
                    agreeing += 1
                rec = {
                    "cls": cls,
                    "offset": "0x%x" % f.offset,
                    "derived": {"type": f.type, "name": f.name, "width": f.width,
                                "file": "%s:%d" % (h.path, f.line)},
                    "base_cls": a,
                    "base": {"type": g.type, "name": g.name, "width": g.width,
                             "file": "%s:%d" % (headers[a].path, g.line)},
                    "base_depth": depth,
                    "base_is_reference": headers[a].kind == "reference",
                    "kind": kind,
                }
                ev = raw.get(cls, {}).get(f.offset)
                if ev is not None and (cls, f.offset) not in raw_multi:
                    w, ty, path, line = ev
                    rec["source_evidence"] = {"width": w, "type": ty,
                                              "file": "%s:%d" % (path, line)}
                    if g.width is not None and w == g.width:
                        rec["agrees_with_source"] = True
                    elif f.width is not None and w == f.width:
                        rec["agrees_with_source"] = False
                    else:
                        rec["agrees_with_source"] = None
                else:
                    if ev is not None:
                        rec["source_evidence"] = {
                            "width": None, "type": "multiple",
                            "file": "src/ shows more than one width at this offset"}
                    rec["agrees_with_source"] = None
                conflicts.append(rec)
    conflicts.sort(key=lambda r: (r["cls"], int(r["offset"], 16), r["base_depth"],
                                  r["base_cls"]))
    kinds = Counter(r["kind"] for r in conflicts)

    # ---- 7. cross-checks against the figures quoted in the plan ----------
    actor_c_half = parse_header(os.path.join(inc, "Actor.h"), "include/Actor.h",
                                cplusplus=False)

    def actor_map(which):
        if which == "c_half":
            m = {}
            for f in actor_c_half.fields:
                m.setdefault(f.offset, f)
            return m
        m = dict(offmap.get("Actor", {}))
        if which == "cpp_plus_bases":
            for a in anc.get("Actor", []):
                for off, fld in offmap.get(a, {}).items():
                    m.setdefault(off, fld)
        return m

    cross = {}
    for label, wb in (("actor_h_cpp_struct_only", "cpp"),
                      ("actor_plus_its_own_bases", "cpp_plus_bases"),
                      ("actor_h_flat_C_struct", "c_half")):
        am = actor_map(wb)
        for scope in ("all_241_bannered", "actor_descendants_only"):
            hits = wc = sc = 0
            for cls in bannered:
                if scope == "actor_descendants_only" and "Actor" not in anc.get(cls, []):
                    continue
                for f in headers[cls].fields:
                    g = am.get(f.offset)
                    if g is None:
                        continue
                    hits += 1
                    if f.width is not None and g.width is not None:
                        if f.width != g.width:
                            wc += 1
                        elif f.sign and g.sign and f.sign != g.sign:
                            sc += 1
            cross["%s__%s" % (label, scope)] = {
                "fields_at_an_offset_Actor_names": hits,
                "width_conflicts": wc,
                "signedness_conflicts": sc,
            }

    U8_BLOCK = (0x8c, 0x8e, 0x90, 0x92, 0x94, 0x96)
    block = [r for r in conflicts if r["kind"] == "width"
             and int(r["offset"], 16) in U8_BLOCK and r["derived"]["width"] == 1
             and r["base"]["width"] == 2]
    block_classes = sorted({r["cls"] for r in block})
    width_conf = [r for r in conflicts if r["kind"] == "width"]
    corrob = [r for r in width_conf if r["agrees_with_source"] is True]
    contra = [r for r in width_conf if r["agrees_with_source"] is False]

    # Classification: is this one bug stamped across the corpus at a handful of
    # offsets, or a long tail of one-offs?  Both need different follow-up.
    by_off = defaultdict(set)
    for r in width_conf:
        by_off[r["offset"]].add(r["cls"])
    rep3 = {o: sorted(cs) for o, cs in by_off.items() if len(cs) >= 3}
    rep2 = {o for o, cs in by_off.items() if len(cs) == 2}
    rep1 = {o for o, cs in by_off.items() if len(cs) == 1}
    classification = {
        "distinct_offsets_involved": len(by_off),
        "conflicts_at_offsets_shared_by_3plus_classes": sum(
            1 for r in width_conf if r["offset"] in rep3),
        "conflicts_at_offsets_shared_by_2_classes": sum(
            1 for r in width_conf if r["offset"] in rep2),
        "conflicts_at_a_one_off_offset": sum(
            1 for r in width_conf if r["offset"] in rep1),
        "derived_narrower_than_base": sum(
            1 for r in width_conf if r["derived"]["width"] < r["base"]["width"]),
        "derived_wider_than_base": sum(
            1 for r in width_conf if r["derived"]["width"] > r["base"]["width"]),
        "derived_is_u8_and_base_is_wider": sum(
            1 for r in width_conf
            if r["derived"]["width"] == 1 and r["base"]["width"] > 1),
        "repeated_offsets": {o: rep3[o] for o in sorted(rep3, key=lambda s: int(s, 16))},
    }

    # ---- 8. assemble ------------------------------------------------------
    return {
        "meta": {
            "pass": "hierarchy",
            "generator": "tools/evidence_hierarchy.py",
            "meaning": {
                "hierarchy[c].base": "the IMMEDIATE base.  ChainChomp's is Enemy, "
                                     "not Actor; Actor is reached at base_depth 2 "
                                     "along hierarchy[c].chain.",
                "conflicts": "one entry per (bannered class, offset, ancestor that "
                             "also names that offset).  kind=width is the "
                             "base-conflict bucket of plan-gen-header section 4. "
                             "kind=agree is corroboration, not a bug.  Padding "
                             "(pad_*) is not a claim and is never compared.",
                "agrees_with_source": "true when a raw offset access still present "
                                      "in that class's own src/ TUs carries the "
                                      "BASE's width (base wins, derived header is "
                                      "wrong); false when it carries the derived "
                                      "header's width; null when src/ says nothing "
                                      "or contradicts itself.",
                "base_is_reference": "true when the ancestor's header is one of the "
                                     "de-bannered, hand-reconstructed references. "
                                     "Those are read-only authority; a conflict "
                                     "against one is a bug in the DERIVED header.",
            },
            "recall": {
                "bannered_headers": len(bannered),
                "reference_headers": len(reference),
                "classes_placed": len(placed),
                "classes_unplaced": len(unplaced),
                "edge_sources": {
                    "reference_header": edge_src_count["reference_header"],
                    "dtor_vptr_chain": edge_src_count["dtor_vptr_chain"],
                    "dtor_chain": edge_src_count["dtor_chain"],
                    "ctor_chain": edge_src_count["ctor_chain"],
                    "cpp_dtor_shim": edge_src_count["cpp_dtor_shim"],
                    "cpp_shim": edge_src_count["cpp_shim"],
                    "rtti": edge_src_count["rtti"],
                    "seed_hier_json": edge_src_count["seed_hier_json"],
                },
                "unplaced": unplaced,
                "unplaced_reasons": reasons,
                "populations": {k: stats[k] for k in sorted(stats)},
                "ancestors_without_a_header": dict(sorted(no_header.items())),
                "confidence_histogram": dict(sorted(
                    Counter(hierarchy[c]["confidence"] for c in placed).items())),
                "hierarchy_entries_total": len(hierarchy),
                "vtable_alias_groups": [g for g in alias_groups],
                "notes": notes + [
                    "rtti now outranks reference_header: an edge the ROM stores as a "
                    "pointer is the answer, not evidence to be weighed. %d of the "
                    "ROM's %d edges are usable here; the rest have an end whose "
                    "vtable carries no _ZTV symbol yet. config holds %d _ZTI "
                    "symbols (tools/rtti_symbols.py). The join is vtable-only on "
                    "purpose -- see load_rtti_edges()."
                    % (stats["rtti_edges_usable"], stats["rtti_edges_in_rom"],
                       stats["symbols_zti"]),
                    "cpp_shim ranks last on purpose: src shims flatten chains "
                    "(src says `struct Actor : ActorBase`; the ROM and "
                    "include/Actor.h say Actor : ActorDerived : ActorBase).",
                    "Fields whose type this pass cannot size (struct-typed members) "
                    "are compared as kind=unknown_width, never as agreement.",
                ],
            },
            "cross_checks": {
                "overlaps_total": len(conflicts),
                "overlap_kind_counts": dict(sorted(kinds.items())),
                "distinct_class_offset_pairs": len(
                    {(r["cls"], r["offset"]) for r in conflicts}),
                "width_conflicts_vs_reference_ancestor": sum(
                    1 for r in width_conf if r["base_is_reference"]),
                "width_conflicts_vs_bannered_ancestor": sum(
                    1 for r in width_conf if not r["base_is_reference"]),
                "width_conflicts_at_base_depth_1": sum(
                    1 for r in width_conf if r["base_depth"] == 1),
                "plan_figure_reproduction": cross,
                "width_conflict_classification": classification,
                "u8_block_0x8c_0x96": {
                    "conflict_count": len(block),
                    "class_count": len(block_classes),
                    "classes": block_classes,
                },
                "seed_hier_json_disagreements": {
                    "entries": len(seed),
                    "agree_with_accepted_base": sum(
                        1 for k, v in sorted(seed.items())
                        if k in hierarchy and hierarchy[k]["base"] == alias.get(v, v)),
                    "contradicted_by_stronger_evidence": sorted(
                        "%s: seed=%s accepted=%s" % (k, v, hierarchy[k]["base"])
                        for k, v in seed.items()
                        if k in hierarchy and hierarchy[k]["base"] != alias.get(v, v)),
                },
                "width_conflicts_corroborated_by_src_raw_offset": len(corrob),
                "width_conflicts_contradicted_by_src_raw_offset": len(contra),
                "width_conflicts_with_no_src_evidence": len(width_conf) - len(corrob) - len(contra),
            },
        },
        "hierarchy": {k: hierarchy[k] for k in sorted(hierarchy)},
        "conflicts": conflicts,
        "overlaps_agreeing": agreeing,
    }


