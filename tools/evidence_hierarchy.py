def function_body(text, symbol):
    """(body, first_param_name, line_of_open_brace) for a *definition*.

    `extern ...;` declarations are skipped: only a `{` after the parameter list
    counts.  Getting this wrong is how the first draft of this pass mistook
    `extern void _ZN9AnimationD1Ev(void *thiz);` for a base-destructor call.
    """
    for m in re.finditer(re.escape(symbol) + r"\s*\(", text):
        i = m.end() - 1
        depth, j = 0, i
        while j < len(text):
            if text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        if j >= len(text):
            continue
        params = text[m.end():j]
        k = j + 1
        while k < len(text) and text[k] in " \t\r\n":
            k += 1
        if k >= len(text) or text[k] != "{":
            continue
        depth, e = 0, k
        while e < len(text):
            if text[e] == "{":
                depth += 1
            elif text[e] == "}":
                depth -= 1
                if depth == 0:
                    break
            e += 1
        first = params.split(",")[0]
        ids = re.findall(r"[A-Za-z_]\w*", first)
        ids = [t for t in ids if t not in TYPE_TOKENS]
        param = ids[-1] if ids else None
        return text[k + 1:e], param, text.count("\n", 0, k) + 1
    return None, None, None


def _value_ident(expr):
    """The single non-type identifier in `expr`, else None.

    `(int*)((char *)self)` -> 'self';  `((int)t)` -> 't';  `t + 0x10` -> None
    (callers reject `+` first);  `a, b` -> None.
    """
    ids = [t for t in re.findall(r"[A-Za-z_]\w*", expr) if t not in TYPE_TOKENS]
    uniq = set(ids)
    return ids[0] if len(uniq) == 1 else None


def _lhs_is_this_at_zero(lhs, param):
    """True for `t[0]`, `((int*)t)[0]`, `*(void**)((char*)t)`, `t->vtable`."""
    if "+" in lhs:
        return False
    lhs = lhs.strip()
    m = re.match(r"^(.*)\[\s*0\s*\]$", lhs, re.S)
    if m:
        return _value_ident(m.group(1)) == param
    if lhs.startswith("*"):
        return _value_ident(lhs[1:]) == param
    m = re.match(r"^([A-Za-z_]\w*)\s*->\s*vtable$", lhs)
    if m:
        return m.group(1) == param
    return False


RHS_SYM = re.compile(r"([A-Za-z_]\w*)\s*(?:\[\s*\])?\s*$")


def analyse_body(text, symbol):
    """Ordered vptr stores and bare-`this` calls of one ctor/dtor definition.

    Returns {"vptrs": [(sym, absline)], "calls": [(fn, absline)], "param": str}
    or None when the file holds no definition of `symbol`.
    """
    body, param, start = function_body(text, symbol)
    if body is None:
        return None
    nocom = re.sub(r"//[^\n]*", " ", strip_block_comments(body))
    vptrs, calls = [], []
    pos = 0
    for stmt in nocom.split(";"):
        stmt_start, pos = pos, pos + len(stmt) + 1
        s = stmt.strip()
        if not s:
            continue
        line = start + nocom.count("\n", 0, stmt_start + (len(stmt) - len(stmt.lstrip())))
        if "=" in s and "==" not in s:
            lhs, _, rhs = s.partition("=")
            if _lhs_is_this_at_zero(lhs, param):
                rhs = re.sub(r"\([^()]*\)", " ", rhs)
                rhs = rhs.replace("&", " ").strip()
                m = RHS_SYM.match(rhs)
                if m and m.group(1) not in TYPE_TOKENS:
                    vptrs.append((m.group(1), line))
                continue
        m = re.match(r"^(?:return\s+)?(?:\([^()]*\)\s*)*([A-Za-z_]\w*)\s*\((.*)\)$",
                     s.replace("\n", " "), re.S)
        if m:
            fn, arg = m.group(1), m.group(2)
            if fn == symbol or fn in ("if", "while", "for", "switch", "return",
                                      "sizeof", "__destroy_arr"):
                continue
            if "," in arg or "+" in arg or "->" in arg or "[" in arg:
                continue
            if param is not None and _value_ident(arg) != param:
                continue
            calls.append((fn, line))
    return {"vptrs": vptrs, "calls": calls, "param": param}


