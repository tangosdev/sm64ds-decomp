SYM_LINE = re.compile(r"^(\S+)\s+kind:(\S+)\s+addr:(0x[0-9a-fA-F]+)")


def load_symbols(root):
    """(module, addr) -> sorted names, plus file and cross-module-collision counts.

    Keyed by MODULE, not by address alone: DS overlays share address space, so
    `_ZTV12FortressWall` (ov021) and `_ZTV9MontyMole` (ov034) can sit at the
    same address without being the same vtable.  Aliasing on the bare address
    merges unrelated classes and silently deletes their edges.
    """
    by_addr = defaultdict(set)
    loc = {}
    dup = set()
    cfg = os.path.join(root, "config")
    files = 0
    for dirpath, _dirs, fnames in os.walk(cfg):
        for f in fnames:
            if f != "symbols.txt":
                continue
            files += 1
            module = os.path.relpath(dirpath, cfg).replace("\\", "/")
            for line in open(os.path.join(dirpath, f), encoding="utf-8",
                             errors="replace"):
                m = SYM_LINE.match(line.strip())
                if not m:
                    continue
                name, addr = m.group(1), int(m.group(3), 16)
                by_addr[(module, addr)].add(name)
                if name in loc and loc[name] != (module, addr):
                    dup.add(name)
                loc[name] = (module, addr)
    return ({k: sorted(v) for k, v in by_addr.items()}, files, len(dup))


