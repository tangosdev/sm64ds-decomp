DATA_SYM = re.compile(r"^data_(?:ov\d+_)?([0-9a-fA-F]{8})$")


def build_vtable_alias_map(addr_names, known_classes):
    """Canonical class name per vtable *name*, and per `data_*` literal.

    Within one module, several _ZTV names can share an address -- the tree's
    name and the ROM's original one (`_ZTV13QuestionBlock` and
    `_ZTV18daObjHatenaBlock_c` are both ov0xx:0x0214e47c; see
    notes/model-rtti-names.md).  Without collapsing those, QuestionBlock appears
    to inherit from itself under another name.  Preference: a name that has an
    include/*.h, then a name that is not the `*_c` ROM spelling, then sorted.
    """
    alias = {}
    data_alias = {}
    groups = []
    for (_mod, _addr), names in sorted(addr_names.items()):
        classes = []
        for n in names:
            if n.startswith("_ZTV"):
                p = split_nested(n[4:])
                if p:
                    classes.append("::".join(p))
        if not classes:
            continue

        def rank(c):
            return (0 if c in known_classes else 1, 1 if c.endswith("_c") else 0, c)
        canon = sorted(classes, key=rank)[0]
        for c in classes:
            alias[c] = canon
        for n in names:
            if DATA_SYM.match(n):
                data_alias.setdefault(n, canon)
        if len(set(classes)) > 1:
            groups.append(sorted(set(classes)))
    return alias, data_alias, groups


def resolve_vtable_symbol(sym, alias, vt_owner, data_alias=None):
    """A vtable literal as spelled in src/ -> class name, plus the method used."""
    if sym.startswith("VTable_"):
        return None, "thunk_table_ignored"      # secondary-base table: ambiguous
    if sym.startswith("_ZTV"):
        p = split_nested(sym[4:])
        if p:
            c = "::".join(p)
            return alias.get(c, c), "ztv_name"
        return None, "ztv_unparsable"
    if data_alias and sym in data_alias:
        return data_alias[sym], "ztv_alias_by_address"
    owners = vt_owner.get(sym)
    if owners and len(owners) == 1:
        c = next(iter(owners))
        return alias.get(c, c), "dtor_vtable_owner"
    return None, "unresolved"


def resolve_dtor_callee(fn, anon_owner, alias):
    m = re.match(r"^_ZN((?:\d+[A-Za-z_0-9]+)+)D([012])Ev$", fn)
    if m:
        p = split_nested(m.group(1))
        if p:
            c = "::".join(p)
            return alias.get(c, c), "named_dtor"
    if fn in anon_owner:
        return anon_owner[fn], "anon_dtor_via_vtable"
    return None, "unresolved"


def resolve_ctor_callee(fn, anon_owner, alias):
    m = re.match(r"^_ZN((?:\d+[A-Za-z_0-9]+)+)C([123])E", fn)
    if m:
        p = split_nested(m.group(1))
        if p:
            c = "::".join(p)
            return alias.get(c, c), "named_ctor"
    if fn in anon_owner:
        return anon_owner[fn], "anon_dtor_via_vtable"
    return None, "unresolved"


