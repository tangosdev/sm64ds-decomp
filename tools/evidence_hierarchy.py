def normalize_type(t: str) -> str:
    t = re.sub(r"\b(const|volatile|struct|union|enum|class)\b", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def type_width(t: str):
    """Bytes, or None when the type is a struct/typedef this pass cannot size."""
    t = normalize_type(t)
    if "*" in t:
        return 4
    return SCALAR_WIDTH.get(t)


def type_signedness(t: str):
    t = normalize_type(t)
    if "*" in t:
        return None          # a pointer vs an s32 is not a signedness bug
    if t in UNSIGNED:
        return "unsigned"
    if t in SIGNED:
        return "signed"
    return None


