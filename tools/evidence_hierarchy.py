_LEN = re.compile(r"(\d+)")


def split_nested(s: str):
    """`10ChainChomp` -> ['ChainChomp'];  `8Particle7Manager` -> both parts."""
    parts, i = [], 0
    while i < len(s):
        m = _LEN.match(s, i)
        if not m:
            return None
        n = int(m.group(1))
        i = m.end()
        if i + n > len(s):
            return None
        parts.append(s[i:i + n])
        i += n
    return parts if parts else None


def header_stem_to_class(stem: str) -> str:
    """include/Particle__Manager.h describes Particle::Manager."""
    return stem.replace("__", "::")


DTOR_FILE = re.compile(r"^_ZN((?:\d+[A-Za-z_0-9]+)+)D([012])Ev\.(c|cpp)$")
CTOR_FILE = re.compile(r"^_ZN((?:\d+[A-Za-z_0-9]+)+)C([12])E.*\.(c|cpp)$")
ANON_FILE = re.compile(r"^(func_[A-Za-z0-9_]+)\.(c|cpp)$")


def class_of_mangled_symbol(sym: str):
    """`_ZN10ChainChomp13InitResourcesEv` -> ChainChomp."""
    if not sym.startswith("_ZN"):
        return None
    body = sym[3:]
    parts, i = [], 0
    while i < len(body):
        m = _LEN.match(body, i)
        if not m:
            break
        n = int(m.group(1))
        j = m.end()
        if j + n > len(body):
            break
        parts.append(body[j:j + n])
        i = j + n
    if not parts:
        return None
    if body[i:i + 2] in ("C1", "C2", "C3", "D0", "D1", "D2"):
        return "::".join(parts)
    if len(parts) == 1:
        return parts[0]
    return "::".join(parts[:-1])


