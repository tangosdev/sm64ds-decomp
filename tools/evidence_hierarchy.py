class Field:
    __slots__ = ("name", "type", "offset", "width", "sign", "line", "count",
                 "offset_source")

    def __init__(self, name, type_, offset, width, sign, line, count, osrc):
        self.name = name
        self.type = type_
        self.offset = offset
        self.width = width
        self.sign = sign
        self.line = line
        self.count = count
        self.offset_source = osrc


class HeaderInfo:
    def __init__(self, cls, path, kind):
        self.cls = cls
        self.path = path          # repo-relative, forward slashes
        self.kind = kind          # bannered | reference | decl | other_generated
        self.base = None          # from `struct D : B`; reference headers only
        self.base_line = None
        self.fields = []          # named, non-pad, offset known
        self.pads = 0
        self.no_offset = 0
        self.unknown_width = 0
        self.struct_found = False


CPP_IF = re.compile(r"^\s*#\s*(ifdef|ifndef|if|else|elif|endif)\b(.*)$")
STRUCT_OPEN = re.compile(
    r"^\s*(?:typedef\s+)?(?:struct|class)\s+([A-Za-z_]\w*)\s*"
    r"(?::\s*(?:public\s+|private\s+|protected\s+|virtual\s+)*([A-Za-z_][\w:]*)\s*)?\{")
FIELD_RE = re.compile(
    r"^\s*(?P<type>(?:const\s+|volatile\s+|struct\s+|union\s+|unsigned\s+|signed\s+)*"
    r"[A-Za-z_][\w:]*(?:\s*\*+)?)\s+"
    r"(?P<name>[A-Za-z_]\w*)\s*(?P<arr>(?:\[[^\]]*\])*)\s*;")
OFFSET_COMMENT = re.compile(r"/\*+\s*(?:0x)?([0-9a-fA-F]{1,4})\b")
NAME_OFFSET = re.compile(r"^(?:unk|field|pad)_([0-9a-fA-F]{2,4})$")


def cpp_view(lines, cplusplus=True):
    """Lines visible with __cplusplus defined (or not), as (lineno, text).

    Only __cplusplus-dependent conditionals are evaluated; every other #if is
    treated as taken (include guards, mostly).  This is what selects Actor.h's
    inheriting C++ struct over its flat C twin; `cplusplus=False` selects the
    other half, which the cross-check matrix needs.
    """
    out = []
    stack = []                      # (is_cpp_conditional, keeping)
    for idx, raw in enumerate(lines, 1):
        m = CPP_IF.match(raw)
        if m:
            kw, rest = m.group(1), m.group(2)
            if kw in ("ifdef", "ifndef", "if"):
                is_cpp = "__cplusplus" in rest
                if kw == "ifdef":
                    keep = cplusplus
                elif kw == "ifndef":
                    keep = not cplusplus
                else:
                    keep = cplusplus if "!defined" not in rest.replace(" ", "") \
                        else not cplusplus
                stack.append((is_cpp, keep if is_cpp else True))
            elif kw == "elif":
                if stack:
                    is_cpp, keep = stack[-1]
                    stack[-1] = (is_cpp, (not keep) if is_cpp else True)
            elif kw == "else":
                if stack:
                    is_cpp, keep = stack[-1]
                    stack[-1] = (is_cpp, (not keep) if is_cpp else True)
            elif kw == "endif":
                if stack:
                    stack.pop()
            continue
        if all(keep for _, keep in stack):
            out.append((idx, raw))
    return out


def strip_block_comments(text):
    return re.sub(r"/\*.*?\*/", " ", text, flags=re.S)


def parse_header(path, relpath, cplusplus=True):
    text = open(path, encoding="utf-8", errors="replace").read()
    if BANNER in text:
        kind = "bannered"
    elif DECL_BANNER in text:
        kind = "decl"
    elif "AUTO-GENERATED" in text:
        kind = "other_generated"
    else:
        kind = "reference"

    stem = os.path.basename(path)[:-2]
    hi = HeaderInfo(header_stem_to_class(stem), relpath, kind)
    if kind in ("decl", "other_generated"):
        return hi

    view = cpp_view(text.split("\n"), cplusplus)
    depth = 0
    in_struct = False
    for lineno, line in view:
        if not in_struct:
            m = STRUCT_OPEN.match(line)
            if m and m.group(1) == stem:
                in_struct = True
                hi.struct_found = True
                if m.group(2):
                    hi.base = m.group(2)
                    hi.base_line = lineno
                depth = line.count("{") - line.count("}")
            continue

        if depth == 1:
            body = strip_block_comments(line)
            if "(" not in body and not re.match(
                    r"\s*(virtual|static|friend|typedef|using|public|private|protected)\b",
                    body):
                fm = FIELD_RE.match(body)
                if fm:
                    tname = fm.group("type").strip()
                    name = fm.group("name")
                    count = 1
                    if fm.group("arr"):
                        for dim in re.findall(r"\[([^\]]*)\]", fm.group("arr")):
                            try:
                                count *= int(dim.strip(), 0)
                            except ValueError:
                                count = None
                                break
                    is_pad = name.startswith("pad") or name.startswith("_pad")
                    off, osrc = None, None
                    om = OFFSET_COMMENT.search(line)
                    if om:
                        try:
                            off, osrc = int(om.group(1), 16), "comment"
                        except ValueError:
                            off = None
                    if off is None:
                        nm = NAME_OFFSET.match(name)
                        if nm:
                            off, osrc = int(nm.group(1), 16), "name"
                    ew = type_width(tname)
                    width = ew * count if (ew is not None and count is not None) else None
                    if is_pad:
                        hi.pads += 1
                    elif off is None:
                        hi.no_offset += 1
                    else:
                        if width is None:
                            hi.unknown_width += 1
                        hi.fields.append(Field(name, normalize_type(tname), off,
                                               width, type_signedness(tname),
                                               lineno, count, osrc))
        depth += line.count("{") - line.count("}")
        if depth <= 0:
            in_struct = False
    return hi


