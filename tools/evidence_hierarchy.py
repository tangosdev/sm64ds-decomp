#!/usr/bin/env python3
"""Pass 2 of notes/plan-gen-header.md -- the *hierarchy* evidence pass.

Two jobs, one output file (build/evidence_hierarchy.json):

  (a) Reconstruct the class hierarchy of the classes described by include/*.h
      from evidence that is checkable, recording per-edge provenance and a
      confidence.  Classes that could not be placed are named, with a reason:
      a wrong parent manufactures false conflicts, so an unplaced class is a
      better output than a guessed one.

  (b) Find every field in an AUTO-GENERATED ("bannered") header that sits at an
      offset one of its ancestors also names, and say whether the two agree on
      width.  Disagreements are the "base-conflict" bucket of plan-gen-header
      section 4: the generated corpus inlined copies of base-class fields
      instead of inheriting them, and the copies often disagree on width.

Nothing is written outside build/.  This pass never proposes a change to a
de-bannered header: those (include/Actor.h, include/Fader.h, ...) were
hand-reconstructed with real inheritance and are the *reference*, read-only.

Evidence sources for an inheritance edge, strongest first
---------------------------------------------------------
reference_header   `struct D : B` in a de-bannered include/*.h.  Hand-verified
                   against the ROM; wins every disagreement.

dtor_vptr_chain    CodeWarrior resets [this+0] to each base subobject's vtable
                   in turn as a destructor unwinds.  `_ZN6CameraD1Ev` stores
                   _ZTV6Camera, _ZTV4View, _ZTV12ActorDerived and then calls
                   _ZN9ActorBaseD2Ev, which spells the whole chain
                   Camera : View : ActorDerived : ActorBase -- *including* the
                   intermediate bases whose own destructors were inlined away.
                   This is the only source-level evidence that recovers those,
                   and it is why `Actor : ActorDerived` is visible at all.

dtor_chain         The last call in `_ZN<D>D1Ev`/`D2Ev` that passes `this` at
                   offset zero is the immediate base's destructor.  Calls that
                   pass `this + 0x...` are member subobjects, not bases.  Some
                   base dtors are unnamed (`func_ov002_020aedbc` in
                   `_ZN6GoombaD1Ev.c`); those are resolved through the vtable
                   literal the unnamed function stores -- see
                   resolve_vtable_symbol() and the anon-dtor fixpoint below.

ctor_chain         Mirror image in `_ZN<D>C1Ev`/`C2Ev`: the base constructor is
                   the *first* call taking bare `this`, and the vptr stores that
                   follow it run base-most first, so the chain is reversed.

cpp_shim           `struct D : B` inside a src/*.cpp.  Weak, and deliberately
                   ranked below the ROM-shaped evidence: these are local compile
                   shims and routinely *flatten* the chain.  src carries
                   `struct Actor : ActorBase`, while the ROM and include/Actor.h
                   both say Actor : ActorDerived : ActorBase.

seed_hier_json     build/hier.json, a partial map from an earlier session.
                   Weakest: it carries the same flattened `"Actor": "ActorBase"`.

rtti               Reported as 0.  config/**/symbols.txt contains no _ZTI symbol
                   -- the ROM's typeinfo was never delinked -- and this pass is
                   deliberately source+config only (extracted/ is gitignored and
                   the ROM is pass 3's authority, not pass 2's).  Real RTTI does
                   exist in the ROM for the model/animation family and is written
                   up in notes/model-rtti-names.md; the `da*_c` / `dExt*_c`
                   names that show up as vtable aliases below come from there.
                   The counter is emitted as 0 rather than omitted so that
                   "could not look" stays distinguishable from "looked, found
                   none" -- see section 2 of the plan.

Recall
------
Section 2 and section 6 of the plan: a pass that silently matches nothing reports
a clean, confident, wrong answer.  Every population this pass touches is counted
-- headers seen, fields parsed, fields skipped and why, classes placed, classes
unplaced and why, ancestors that have no header at all, source files read.
`--report` prints all of that first, before any finding.

Pure stdlib.  Deterministic: every collection is sorted before it is emitted.
"""

