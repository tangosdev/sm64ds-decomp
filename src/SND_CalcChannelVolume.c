u16 SND_CalcChannelVolume(s32 x) {
    u8 resultLo;
    int resultHi;
    if (x < -723)
        x = -723;
    else if (x > 0)
        x = 0;
    resultLo = data_02086484[x + 723];
    if (x < -240)
        resultHi = 3;
    else if (x < -120)
        resultHi = 2;
    else if (x < -60)
        resultHi = 1;
    else
        resultHi = 0;
    return (resultLo | (resultHi << 8));
}
