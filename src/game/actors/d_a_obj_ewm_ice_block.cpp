int daObjEwmIceBlock_c::Behavior()
{
    Vector3 prev;
    Vector3 node;
    Vector3 diff;
    Vector3 scaled1;
    Vector3 scaled2;
    int looped;
    int delta;
    int len;

    mHorzSpeed = 0xa000;
    delta = mPathNodeIdx - mPathDir;
    looped = 0;

    if (mPath.Loops()) {
        if (mPathDir > 0) {
            if (delta < 0)
                delta = (int)mPath.NumNodes() - 1;
        } else {
            if (delta >= (int)mPath.NumNodes())
                delta = 0;
        }
        mPath.GetNode(node, delta);
    } else {
        if (delta < 0 || delta >= (int)mPath.NumNodes()) {
            node.x = mPos.x;
            node.y = mPos.y;
            node.z = mPos.z;
        } else {
            mPath.GetNode(node, delta);
        }
    }

    mPath.GetNode(prev, mPathNodeIdx);
    Vec3_Sub(&diff, &mPos, &prev);
    len = VEC_Mag(&diff);
    if (len == 0 || len <= mHorzSpeed) {
        int q = FX_Div(mHorzSpeed, len);
        Vec3_MulScalar(&scaled1, &diff, q);
        VEC_Subtract(&mPos, &scaled1, &mPos);
        looped = 1;
    } else {
        int q = FX_Div(mHorzSpeed, len);
        Vec3_MulScalar(&scaled2, &diff, q);
        VEC_Subtract(&mPos, &scaled2, &mPos);
    }

    if (looped) {
        mPathNodeIdx += mPathDir;
        if (mPathNodeIdx < 0) {
            if (mPath.Loops())
                mPathNodeIdx = (int)mPath.NumNodes() - 1;
            else {
                mPathDir = 1;
                mPathNodeIdx += mPathDir * 2;
            }
        }
        if (mPathNodeIdx >= (int)mPath.NumNodes()) {
            if (mPath.Loops())
                mPathNodeIdx = 0;
            else {
                mPathDir = -1;
                mPathNodeIdx += mPathDir * 2;
            }
        }
    }

    UpdateModelPosAndRotY();
    UpdateClsnPosAndRot();
    IsClsnInRange(0x5dc000, 0);
    return 1;
}

int daObjEwmIceBlock_c::InitResources()
{
    mModel.SetFile(dExtSimpleModel_c::LoadFile(*data_ov056_02113314.model), 1, -1);
    UpdateModelPosAndRotY();
    UpdateClsnPosAndRot();
    mMeshCollider.SetFile(dBgW_Kc::LoadFile(*data_ov056_02113314.collision), mClsnMat, 0x199,
                          mAngle.y, *data_ov056_02113314.clps);
    mMeshCollider.SetBeforeClsnCallback(&dBgW::UpdatePosWithTransform);
    mPath.FromID(param1 & 0xff);
    mPathDir = 1;
    mHorzSpeed = 0xa000;
    return 1;
}

