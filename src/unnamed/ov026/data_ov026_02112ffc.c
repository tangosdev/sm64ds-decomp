/* Definition order is what makes the compiler's size sort match address order. */

/* Widths the level loaders walk. Same layouts as LVL_Overlay; this file
 * stays C. */
typedef struct ObjSubTable {
    u8 categoryAndStar;
    u8 count;
    u8 pad[2];
    void *entries;
} ObjSubTable;

typedef struct DoorEntry {
    s16 x;
    s16 y;
    s16 z;
    s16 angle;
    u16 param;
    u16 type;
} DoorEntry;

typedef struct ExitRow {
    s16 x;
    s16 y;
    s16 z;
    s16 rotX;
    s16 rotY;
    u8 param[4];
    u16 pad;
} ExitRow;

typedef struct ViewRow {
    u8 type;
    u8 p1;
    s16 x;
    s16 y;
    s16 z;
    u8 pad_8[2];
    s16 angleY;
    u8 tail[2];
    u16 pad;
} ViewRow;

typedef struct FogRow {
    u8 enabled;
    u8 r;
    u8 g;
    u8 b;
    u16 nearDist;
    u16 farDist;
} FogRow;

typedef struct StandardEntry {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
    s16 rotX;
    s16 rotY;
    s16 rotZ;
    u16 param;
} StandardEntry;

typedef struct SimpleEntry {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
} SimpleEntry;

typedef struct PathNode {
    s16 x;
    s16 y;
    s16 z;
} PathNode;

/* 45 nodes, then the two zero bytes before 0x021132b0. */
typedef struct PathRun {
    PathNode node[45];
    u16 pad;
} PathRun;

typedef struct ClpsBlock {
    u32 tag;
    u16 stride;
    u16 count;
    struct CLPS entries[16];
    u32 tail[6];
} ClpsBlock;

