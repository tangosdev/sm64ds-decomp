typedef char LevelRec_size[sizeof(LevelRec) == 0x1c ? 1 : -1];
typedef char ExitEntry_size[sizeof(ExitEntry) == 0xe ? 1 : -1];
typedef char ClpsBlock_size[sizeof(ClpsBlock) == 0xc0 ? 1 : -1];

