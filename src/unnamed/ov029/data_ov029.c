/* LoadObjects steps these. categoryAndStar is the byte the loader splits
 * into a handler index and a star filter; count is the byte at +1. */
typedef struct {
    u8 categoryAndStar;
    u8 count;
    u8 pad[2];
    void *entries;
} ObjSubTable;

/* LoadSimpleObjects. */
typedef struct {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
} SimpleEntry;

/* LoadStandardObjects and LoadEntranceObjects. rot is the Vector3s the
 * spawn passes through. */
typedef struct {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
    Vector3s rot;
    u16 param;
} StandardEntry;

/* SetViewObjs steps 0xe. The two bytes at +8 and the half at +0xc stay
 * unread; they are the pad the stride still counts. */
