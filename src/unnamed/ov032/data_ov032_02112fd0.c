/* Definition order is what makes the compiler's size sort match address order. */

/* LoadObjects steps these. categoryAndStar is the byte the loader splits
 * into a handler index and a star filter; count is the byte at +1. */
typedef struct {
    u8 categoryAndStar;
    u8 count;
    u8 pad[2];
    void *entries;
} ObjSubTable;

/* LoadSimpleObjects. */
typedef struct {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
} SimpleEntry;

/* LoadStandardObjects and LoadEntranceObjects. rot is the Vector3s the
 * spawn passes through. */
typedef struct {
    u16 raw;
    s16 x;
    s16 y;
    s16 z;
    Vector3s rot;
    u16 param;
} StandardEntry;

/* LoadExitObjects. param is the big-endian word the loader assembles. */
typedef struct {
    s16 x;
    s16 y;
    s16 z;
    s16 rotX;
    s16 rotY;
    u8 param[4];
} ExitEntry;

/* SetViewObjs steps 0xe bytes and does not name a field inside one. */
typedef struct {
    u8 raw[0xe];
} ViewRecord;

/* LoadPathNodeObjects forwards the array. Each node is one Vector3s. */
typedef struct {
    s16 x;
    s16 y;
    s16 z;
} PathNode;

typedef struct {
    u32 tag;
    u16 stride;
    u16 count;
    struct CLPS entries[29];
    u32 tail[4];
} Clps29;

typedef struct {
    ExitEntry exits[5];
    u16 pad;
} Exits5;

typedef struct {
    ViewRecord views[9];
    u16 pad;
} Views9;

typedef struct {
    PathNode nodes[27];
    u16 pad;
} Nodes27;

