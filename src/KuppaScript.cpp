/* The Kuppa script interpreter: the cutscene sequencer behind the intro, the
 * castle-fall scene, the star-get camera moves, the ending flight and the
 * staff roll. One TU: arm9 .text 0x0200e494..0x0200f0bc, its static
 * initializer (.init 0x02073e6c), the scripts (.data 0x0208751c..0x0208a0e0)
 * and the state in .bss 0x0209b270..0x0209b2e4.
 *
 * A script is a run of variable-length command records, ended by a record
 * of size 0:
 *
 *   +0  u8   size of this record in bytes
 *   +1  u8   command (KuppaScriptCommand)
 *   +2  s16  first frame the command runs on, unaligned
 *   +4  s16  last frame, unaligned; negative means "until the script ends"
 *   +6  ...  the command's arguments, unaligned
 *
 * Every frame ProcessKuppaScript walks the whole running script and runs
 * each record whose window holds gKuppaScriptFrame. A record keeps the
 * script alive while it is still to come or open-ended; once none does,
 * and no level load is pending, the script ends.
 *
 * Commands 0..3 drive a player (the command is the character) through
 * Player's own command table; 4 drives the camera's; 0x12 and up drive a
 * daDemo_c cutscene actor whose param1 is the command. ProcessKuppaScript
 * handles the rest itself.
 *
 * The scripts, the camera paths their camera records name and the
 * star-camera table are this file's .data. A record that names another
 * script or a path holds its address, unaligned; an address is not a
 * constant byte, so the static initializer stores each one byte by byte at
 * boot. It also constructs data_0209b294, the fader this file drives.
 *
 * mwccarm lays out a TU's .data and .bss objects by size: a heapsort over
 * the reversed definition order. The patched scripts below are defined in
 * the order retail's initializer stores them, every script after the
 * scripts and paths it names, and the fader after all of them. That order
 * reproduces retail's .bss but not its .data, so the manifest places each
 * .data object at its retail address. The original order is not
 * recoverable. gRunningKuppaScript and gSavedKuppaScript are not here:
 * they sit in a second .bss run (0x0209fc48), apart from this file's
 * other state, and one object cannot place a definition in two runs.
 *
 * The file is ROM-ascending under `#pragma defer_codegen off`, which also
 * keeps ProcessKuppaScript's opt_common_subs bracket to that one function.
 */

