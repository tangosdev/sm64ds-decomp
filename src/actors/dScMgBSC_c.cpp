/* ROM ordinal 5 -- _ZN10dScMgBSC_c18StateTableReactionEv, 0x02124b58, size 0x5c */
/* -------------------------------------------------------------------------- */
// @symbol _ZN10dScMgBSC_c18StateTableReactionEv
/* Table entries 7 and 8, the win and loss table reactions: entry 7
 * queues the table's win animation (func_ov006_020c0c80) and moves to
 * state 9, entry 8 the loss animation (func_ov006_020c0d68) and state
 * 0xa -- the StateWaitTable pair.
 * No code in this TU ever stores 7 or 8 into mState: the judge jumps
 * straight to 0xd (StateDone) and queues the same animations inline,
 * and StateDone (13) is revived into 9/0xa by OnTurnIntoEgg, the vtable
 * slot the engine calls at round end. Both entries are live in the
 * table -- read off __sinit_ov006_0213326c's pair globals -- and the
 * dispatch would reach them if mState were ever set to 7 or 8, but no
 * such writer exists in the recovered code. The handlers are kept
 * byte-exact rather than deleted for that reason. */
void dScMgBSC_c::StateTableReaction()
{
    if (mState == 7) {
        func_ov006_020c0c80(mTable);
        mState = 9;
    } else {
        func_ov006_020c0d68(mTable);
        mState = 0xa;
    }
}

