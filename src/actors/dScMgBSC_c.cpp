/* ROM ordinal 3 -- _ZN10dScMgBSC_c16StateReturnCardsEv, 0x02124a08, size 0xdc */
/* -------------------------------------------------------------------------- */
// @symbol _ZN10dScMgBSC_c16StateReturnCardsEv
/* Table entry 11, reached from StateWaitTable's loss half (0xa). With
 * the game-mode gate data_ov004_020bf9e4 open and the base score still
 * spent (unk_0a8 <= 0), walks both cards' y back to the deck position
 * -0x40000 through Math_Function_0203b14c -- the same approach helper
 * StateWaitDeal used to deal them out -- counting each card once its
 * ride home finishes (the helper returns 0 on arrival). Only when both
 * have made it does the round fully close: the HUD is refreshed
 * (func_ov004_020b0a38) and the machine settles into 0xc (StateDone).
 * The card walk is a pointer step (pos++), and the lane count is read
 * straight from mDealCount every iteration -- the helper owns that
 * counter and the reload is the ROM's own. */
void dScMgBSC_c::StateReturnCards()
{
    int done;
    int i;
    CardPos *pos;

    if (data_ov004_020bf9e4 != 1)
    {
        return;
    }
    if (unk_0a8 <= 0)
    {
        done = 0;
        i = 0;
        if (mDealCount > 0)
        {
            pos = &mCardPos[0];
            do
            {
                if (Math_Function_0203b14c((int *)pos, -0x40000, 0x800, 0xc000, 0x200) == 0)
                {
                    done++;
                }
                i++;
                pos++;
            } while (i < mDealCount);
        }
        if (done < 2)
        {
            return;
        }
    }
    func_ov004_020b0a38();
    mState = 0xc;
}

