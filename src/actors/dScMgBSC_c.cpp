/* State 5: the flip. Four frames of reveal (mRevealStep) first, then both
 * cards' frames advance together until the *other* card finishes its flip
 * (mCardFrame[mOtherCard]) -- the card the player did not pick is the one
 * the reveal is drawn out on. Then the 30-frame judge timer is primed, the
 * machine advances to state 6 (StateJudgeCards), the prompt is dismissed,
 * and the stakes move now: chosen card's value against the other's, with
 * unk_0a8 (the base score) doubling the table's payout
 * (data_ov004_020bfa18 * 2) on a win while mHudScore takes it in either
 * direction (func_ov004_020ad79c).
 * One of the two #pragma opt_strength_reduction carriers -- see the
 * file-top note. */
void dScMgBSC_c::StateRevealCards()
{
    int i;
    mRevealStep += 1;
    if (mRevealStep < 4)
        return;
    mRevealStep = 0;
    for (i = 0; i < 2; i++)
        mCardFrame[i] += 1;
    if (mCardFrame[mOtherCard] < 4)
        return;
    mStateTimer = 0x1e;
    mState += 1;
    mPromptEnabled = 0;
    {
        u8 chosen = mCardValue[mChosenCard];
        u8 other = mCardValue[mOtherCard];
        int c = unk_0a8;
        int d = mHudScore;
        if (chosen > other) {
            c += data_ov004_020bfa18 * 2;
            d = d + 1;
        } else {
            d = d - 1;
        }
        func_ov004_020ad79c(c, d);
    }
}

