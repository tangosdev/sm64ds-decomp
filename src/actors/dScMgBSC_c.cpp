/* ROM ordinal 4 -- _ZN10dScMgBSC_c14StateWaitTableEv, 0x02124ae4, size 0x74 */
/* -------------------------------------------------------------------------- */
// @symbol _ZN10dScMgBSC_c14StateWaitTableEv
/* Table entries 9 and 10, reached from StateDone when OnTurnIntoEgg
 * confirms the round is ending (mode 4 -> 9, mode 5 -> 0xa). Waits for
 * the table's reaction animation to finish (func_ov006_020c1718 on
 * mTable; anything still running returns), then the two halves split:
 * state 9 pays out the win -- the table's base payout doubled
 * (data_ov004_020bfa18 << 1) -- and settles into 0xc (StateDone);
 * state 0xa plays the loss sting (func_ov004_020b5ed0) and moves to
 * 0xb (StateReturnCards) to gather the cards back up. */
void dScMgBSC_c::StateWaitTable()
{
    if (func_ov006_020c1718((int *)mTable) == 0)
        return;
    if (mState == 9) {
        func_ov004_020b56c8(data_ov004_020bfa18 << 1);
        mState = 0xc;
    } else {
        func_ov004_020b5ed0();
        mState = 0xb;
    }
}

