// @symbol _ZN10dScMgBSC_c14StateDealCardsEv
/* State 0: deal the five shuffled cards out to the two lanes. Each card
 * gets a distinct random value (RandomIntInternal, mod 5, rerolled while
 * the value is already taken -- flags[] is the taken-set), both cards
 * start from the same pair of fixed-point positions (0x80000,
 * -0x40000), the deal animation starts (func_ov006_020c1604 on mTable,
 * counting mDealCount), and the prompt trio is primed if it has not run
 * yet. The state machine then advances to state 1 (StateWaitDeal).
 * One of the two #pragma opt_strength_reduction carriers -- see the
 * file-top note. */
void dScMgBSC_c::StateDealCards()
{
    unsigned char flags[5];
    unsigned char* p;
    int j;
    int i;
    unsigned char idx;

    p = flags;
    for (j = 0; j < 5; j++)
        *p++ = 0;

    for (i = 0; i < 2; i++) {
        mCardPos[i].x = 0x80000;
        mCardPos[i].y = -0x40000;
        idx = ((unsigned int)RandomIntInternal(&data_0209e650) >> 16) % 5u;
        for (;;) {
            if (flags[idx] == 0) {
                mCardValue[i] = idx;
                flags[idx] = 1;
                break;
            }
            idx++;
            idx %= 5;
        }
        mCardFrame[i] = 0;
    }

    mOtherCard = 0;
    mChosenCard = 1;
    mDealCount = 0;
    func_ov006_020c1604((char *)mTable, 3, 2, (int)&mDealCount);

    if (mPromptBlinkCount == 0) {
        mPromptEnabled = 1;
        mPromptBlinkCount = 1;
        mPromptBlinkTimer = 0;
    }

    mState += 1;
}

