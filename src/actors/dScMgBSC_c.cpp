/* State 3: slide the two cards to their face-down resting spots. The
 * chosen card's y approaches 0x90000, the other's 0x30000, both at
 * 0x4000 per frame (ApproachLinear returns 0 once arrived); when both
 * have arrived, the 30-frame reveal timer is primed and the machine
 * advances to state 4 (StateWaitMove). */
void dScMgBSC_c::StateMoveCards()
{
    int a = ApproachLinear(mCardPos[mChosenCard].y, 0x90000, 0x4000) & 1;
    int b = ApproachLinear(mCardPos[mOtherCard].y, 0x30000, 0x4000) & 1;

    if (a == 0) return;
    if (b == 0) return;

    mStateTimer = 0x1e;
    mState += 1;
}

