/* ROM ordinal 6 -- _ZN10dScMgBSC_c15StateJudgeCardsEv, 0x02124bb4, size 0x100 */
/* -------------------------------------------------------------------------- */
// @symbol _ZN10dScMgBSC_c15StateJudgeCardsEv
/* State 6: the verdict, 30 frames after the flip. The chosen card's face
 * against the other's, compared as unsigned bytes (mCardValue). On a
 * win the score climbs toward its 0x270f cap, the high-water mark
 * (unk_0b8) is lifted, the score is posted (func_ov004_020adb1c) and
 * jingle 4 plays; on a loss the score pays back down toward 0 and jingle
 * 5 plays. Either way a reaction is queued on the table --
 * func_ov006_020c0c80 for the win, func_ov006_020c0d68 for the loss --
 * and mState moves to 0xd, StateDone's second half (the pair 12/13 it
 * shares in the table).
 * The score bump is spelled through p = &mHudScore deliberately: the
 * ROM materializes the member's address for that read-modify-write
 * (add r1, r4, #0xb4) instead of hitting it directly, and only the
 * pointer spelling reproduces it. */
void dScMgBSC_c::StateJudgeCards()
{
    int *p;

    mStateTimer = mStateTimer - 1;
    if (mStateTimer > 0)
        return;

    if (mCardValue[mChosenCard] > mCardValue[mOtherCard])
    {
        if (mHudScore < 0x270f)
        {
            p = &mHudScore;
            *p = *p + 1;
        }
        if (mHudScore > unk_0b8)
            unk_0b8 = mHudScore;
        func_ov004_020adb1c(mHudScore);
        func_ov004_020b0a54(4);
        func_ov006_020c0c80(mTable);
        mState = 0xd;
    }
    else
    {
        if (mHudScore > 0)
        {
            p = &mHudScore;
            *p = *p - 1;
        }
        func_ov004_020b0a54(5);
        func_ov006_020c0d68(mTable);
        mState = 0xd;
    }
}

