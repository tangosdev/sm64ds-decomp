/* State 2: wait for the touch. The touch driver's published sample
 * (data_020a0e40 and the data_020a0de8 byte rows) is hit-tested against
 * each lane: the lane's dealt x position (data_ov006_0213fd44, the same
 * targets StateWaitDeal approached, read back at 1:4096) within 16
 * pixels, and y within 24 pixels of 0x60. The lane touched becomes
 * mChosenCard, the other mOtherCard, the reveal step restarts, and the
 * machine advances to state 3 (StateMoveCards) with the pick sound. */
void dScMgBSC_c::StateChooseCard()
{
    unsigned int i = data_020a0e40;
    int ok = 0;
    int sb;
    if (data_020a0de8[i * 4] != 0) {
        if (data_020a0de9[i * 4] != 0) ok = 1;
    }
    if (ok == 0) return;
    for (sb = 0; sb < 2; sb++) {
        unsigned char idx = *(volatile unsigned char *)&data_020a0e40;
        unsigned char *b = &data_020a0de8[(unsigned int)idx * 4];
        int v = (int)b[2] - (data_ov006_0213fd44[sb] >> 12);
        int w = (int)b[3] - 0x60;
        if (v < -0x10) continue;
        if (v > 0x10) continue;
        if (w < -0x18) continue;
        if (w > 0x18) continue;
        mChosenCard = sb;
        mOtherCard = sb ^ 1;
        mRevealStep = 0;
        mState += 1;
        data_ov004_020bf9ec = 1;
        Sound::PlayBank2_2D(0x153);
    }
}

