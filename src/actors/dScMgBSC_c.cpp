// @symbol _ZN10dScMgBSC_c13StateWaitDealEv
/* State 1: wait for the deal animation. Each lane's card approaches its
 * own target (Math_Function_0203b14c on the card's x, and on y toward
 * 0x60000; the x targets are the two deal lanes from
 * data_ov006_0213fd44); mDealCount is the number of lanes still
 * animating, re-read every iteration because the animation helper
 * decrements it. When both lanes arrive the state machine advances to
 * state 2 (StateChooseCard). */
void dScMgBSC_c::StateWaitDeal()
{
  int i;
  int fp;
  int sl;
  char *p;
  char *q;
  short count;

  fp = 0;
  i = 0;
  count = mDealCount;
  if (count <= 0)
    goto after_loop;

  p = (char *)&mCardPos[0].x;
  q = (char *)&mCardPos[0].y;
  do {
    if (Math_Function_0203b14c((int *)p, data_ov006_0213fd44[i], 0x800, 0x10000, 0x200) == 0)
      sl = 1;
    else
      sl = 0;

    if (Math_Function_0203b14c((int *)q, 0x60000, 0x800, 0x10000, 0x200) == 0)
    {
      if (sl != 0)
        fp++;
    }
    p += 8;
    q += 8;
    i++;
    count = mDealCount;
  } while (i < count);

after_loop:
  if (fp < 2)
    return;
  mState++;
}

